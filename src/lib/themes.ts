function createTheme(
  id: string,
  name: string,
  isDark: boolean,
  overrides: Record<string, string>
): ThemeDefinition {
  const base = isDark ? BASE_DARK : BASE_LIGHT;
  const vars = { ...base, ...overrides };
  return {
    id,
    name,
    isDark,
    vars,
    swatches: [
      vars['--bg-base'],
      vars['--accent'] || vars['--user-bubble-bg'],
      vars['--sidebar-bg'],
      vars['--text-base'],
    ],
  };
}

